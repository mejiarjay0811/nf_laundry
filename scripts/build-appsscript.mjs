/**
 * Compiles the backend into a single file Apps Script can run.
 *
 * The point of this build is that the code deployed to Apps Script is the same
 * tested TypeScript the Node server runs — the services, the money arithmetic,
 * the validators and the route table — rather than a hand-written copy that
 * would quietly drift out of step.
 *
 * Two things make that possible:
 *
 *   Shims.  A handful of modules genuinely cannot cross over — the environment
 *           reader, and the storage driver picker that imports googleapis and
 *           node:fs. Each is swapped for an Apps Script equivalent at bundle
 *           time, so nothing else has to know which runtime it is on.
 *
 *   Target. Apps Script has no event loop, and doPost must return its value
 *           before any promise callback would normally run. Compiling to ES2016
 *           lowers async/await onto generators driven by the *global* Promise,
 *           which the runtime replaces with a synchronous one. See
 *           appsscript-src/syncPromise.ts.
 *
 * Usage:  npm run build:appsscript
 */
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'apps-script', 'Bundle.gs');

/** Modules replaced with an Apps Script implementation, keyed by source path. */
const SHIMS = {
  'server/env.js': 'appsscript-src/env.ts',
  'server/sheets/index.js': 'appsscript-src/store.ts',
};

const shimPlugin = {
  name: 'apps-script-shims',
  setup(build) {
    build.onResolve({ filter: /\.js$/ }, (args) => {
      if (!args.importer) return null;
      const absolute = path.resolve(path.dirname(args.importer), args.path);
      const relative = path.relative(root, absolute).split(path.sep).join('/');
      const shim = SHIMS[relative];
      return shim ? { path: path.join(root, shim) } : null;
    });
  },
};

/** Anything from these would mean a Node-only module slipped into the bundle. */
const FORBIDDEN = [
  { pattern: /\brequire\s*\(/, label: 'require(' },
  { pattern: /\bprocess\s*\.\s*(env|exit|version|uptime|cwd)/, label: 'process.*' },
  { pattern: /\bBuffer\s*\./, label: 'Buffer.' },
  { pattern: /from\s*['"]node:/, label: "import 'node:...'" },
  { pattern: /\bdocument\s*\.\s*(createElement|querySelector|getElementById)/, label: 'document.*' },
  { pattern: /\bnew\s+XMLHttpRequest\b/, label: 'XMLHttpRequest' },
];

const FOOTER = `
/*
 * Apps Script entry points.
 *
 * The bundle above is an IIFE, so these top-level declarations are what the
 * runtime actually finds and calls.
 */
function doPost(e) {
  return globalThis.__nfDoPost(e);
}

function doGet(e) {
  return globalThis.__nfDoGet(e);
}
`;

async function main() {
  const result = await build({
    entryPoints: [path.join(root, 'appsscript-src', 'main.ts')],
    bundle: true,
    format: 'iife',
    // Lowers async/await onto the global Promise; see the note above.
    target: 'es2016',
    platform: 'neutral',
    mainFields: ['module', 'main'],
    conditions: ['import', 'default'],
    plugins: [shimPlugin],
    write: false,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'warning',
  });

  const [output] = result.outputFiles;
  const code = output.text;

  const problems = FORBIDDEN.filter(({ pattern }) => pattern.test(code)).map(({ label }) => label);
  if (problems.length > 0) {
    console.error('\nThe bundle contains constructs Apps Script cannot run:');
    for (const problem of problems) console.error('  - ' + problem);
    console.error('\nA Node-only module has most likely been pulled in. Add a shim in');
    console.error('appsscript-src/ and register it in SHIMS above.\n');
    process.exit(1);
  }

  const header =
    '/*\n' +
    ' * N & F LAUNDRY POS — generated backend. Do not edit this file.\n' +
    ' *\n' +
    ' * Built from appsscript-src/main.ts by scripts/build-appsscript.mjs.\n' +
    ' * Rebuild with:  npm run build:appsscript\n' +
    ' *\n' +
    ' * Built: ' + new Date().toISOString() + '\n' +
    ' */\n\n';

  await writeFile(outFile, header + code + FOOTER, 'utf8');

  const kb = (Buffer.byteLength(header + code + FOOTER) / 1024).toFixed(1);
  const version = (await readFile(path.join(root, 'appsscript-src', 'main.ts'), 'utf8')).match(
    /SCRIPT_VERSION\s*=\s*'([^']+)'/,
  );

  console.log('Wrote apps-script/Bundle.gs  (' + kb + ' KB, script version ' + (version?.[1] ?? '?') + ')');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
